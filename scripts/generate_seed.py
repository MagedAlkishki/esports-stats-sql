#!/usr/bin/env python3
"""Generate a deterministic seed.sql for esports-stats-sql.

This is run once by a human (or re-run after editing the generation rules)
to produce the committed `seed/seed.sql` file -- it is NOT run by the tests.
The tests load the *committed* seed.sql so the dataset stays fixed and
query results stay reproducible; nothing about the test suite's correctness
depends on this script executing correctly at test time.

Everything is driven by random.Random(42), so re-running this script with
no changes reproduces byte-identical output.
"""
import random
import sys
from pathlib import Path

RNG = random.Random(42)

REGIONS = ["NA", "EU", "APAC", "MENA"]
ROLES = ["Entry Fragger", "Support", "Anchor", "Flex", "IGL"]
MAPS = ["Ascent", "Bind", "Haven", "Icebox", "Lotus", "Sunset", "Breeze"]

TEAM_NAMES = [
    ("Nightfall Esports", "NA"),
    ("Iron Horizon", "NA"),
    ("Velvet Static", "EU"),
    ("Granite Wolves", "EU"),
    ("Crimson Drift", "APAC"),
    ("Solace Rising", "MENA"),
]

GAMERTAG_SYLLABLES = [
    "zer", "kyo", "vex", "nim", "ash", "ryu", "fel", "dax", "mir", "kol",
    "tov", "nex", "pyr", "sol", "vak", "quin", "orn", "thal", "rix", "bask",
]


def make_gamertag(used: set) -> str:
    while True:
        tag = "".join(RNG.choice(GAMERTAG_SYLLABLES) for _ in range(2)).capitalize()
        suffix = RNG.choice(["", "", str(RNG.randint(1, 99))])
        tag = f"{tag}{suffix}"
        if tag not in used:
            used.add(tag)
            return tag


def sql_str(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def main() -> None:
    out = []
    out.append("-- esports-stats-sql seed data")
    out.append("-- Deterministically generated by scripts/generate_seed.py (seed=42).")
    out.append("-- Do not hand-edit; re-run the generator and commit its output instead.")
    out.append("")
    out.append("PRAGMA foreign_keys = ON;")
    out.append("")

    # ---- teams ----
    out.append("-- teams")
    teams = []  # list of (id, name, region)
    for i, (name, region) in enumerate(TEAM_NAMES, start=1):
        teams.append((i, name, region))
        out.append(
            f"INSERT INTO teams (team_id, name, region) VALUES "
            f"({i}, {sql_str(name)}, {sql_str(region)});"
        )
    out.append("")

    # ---- players: 5 per team, one of each role ----
    out.append("-- players")
    players = []  # list of dicts
    used_tags = set()
    pid = 1
    for team_id, team_name, _region in teams:
        for role in ROLES:
            tag = make_gamertag(used_tags)
            players.append({"id": pid, "tag": tag, "team_id": team_id, "role": role})
            out.append(
                f"INSERT INTO players (player_id, gamertag, team_id, role) VALUES "
                f"({pid}, {sql_str(tag)}, {team_id}, {sql_str(role)});"
            )
            pid += 1
    out.append("")

    # Role skill multipliers: entry fraggers/duelist-types rack up more
    # kills and more deaths (aggressive), anchors/IGLs play fewer high-kill
    # rounds, support sits in between but leans toward assists.
    ROLE_PROFILE = {
        "Entry Fragger": {"kills": (14, 24), "deaths": (14, 20), "assists": (2, 6)},
        "Flex":          {"kills": (12, 20), "deaths": (12, 18), "assists": (3, 7)},
        "Support":       {"kills": (8, 15),  "deaths": (11, 17), "assists": (6, 12)},
        "Anchor":        {"kills": (9, 16),  "deaths": (10, 16), "assists": (3, 7)},
        "IGL":           {"kills": (7, 14),  "deaths": (10, 16), "assists": (5, 10)},
    }

    # ---- tournaments ----
    out.append("-- tournaments")
    tournaments = [
        (1, "Ember Circuit", "2025 Split 1", "2025-02-03"),
        (2, "Ember Circuit", "2025 Split 2", "2025-07-14"),
    ]
    for tid, name, season, start_date in tournaments:
        out.append(
            f"INSERT INTO tournaments (tournament_id, name, season, start_date) VALUES "
            f"({tid}, {sql_str(name)}, {sql_str(season)}, {sql_str(start_date)});"
        )
    out.append("")

    team_ids = [t[0] for t in teams]
    players_by_team = {tid: [p for p in players if p["team_id"] == tid] for tid in team_ids}

    out.append("-- matches, match_maps, player_match_stats")
    match_id = 1
    match_map_id = 1
    stat_id = 1
    match_rows = []
    map_rows = []
    stat_rows = []

    for tournament_id, _name, _season, start_date in tournaments:
        year, month, day = (int(p) for p in start_date.split("-"))
        # Full single round-robin among the 6 teams for this tournament.
        pairings = []
        for i in range(len(team_ids)):
            for j in range(i + 1, len(team_ids)):
                pairings.append((team_ids[i], team_ids[j]))
        RNG.shuffle(pairings)

        day_offset = 0
        for team_a_id, team_b_id in pairings:
            day_offset += RNG.choice([1, 2, 3])
            # crude but valid date rollover across these short seasons
            total_day = day + day_offset
            m = month
            y = year
            while total_day > 28:
                total_day -= 28
                m += 1
                if m > 12:
                    m = 1
                    y += 1
            match_date = f"{y:04d}-{m:02d}-{total_day:02d}"

            # Best-of-3: play maps until one side reaches 2 map wins.
            a_wins = 0
            b_wins = 0
            map_order = 1
            available_maps = MAPS[:]
            RNG.shuffle(available_maps)
            maps_this_match = []
            while a_wins < 2 and b_wins < 2:
                map_name = available_maps[(map_order - 1) % len(available_maps)]
                # Slight home-advantage-free coin flip, mildly weighted by
                # a per-match "form" roll so results aren't perfectly 50/50.
                winner = team_a_id if RNG.random() < 0.52 else team_b_id
                if winner == team_a_id:
                    a_wins += 1
                else:
                    b_wins += 1
                maps_this_match.append((map_order, map_name, winner))
                map_order += 1

            match_rows.append(
                (match_id, tournament_id, match_date, team_a_id, team_b_id, a_wins, b_wins)
            )

            for order, map_name, winner in maps_this_match:
                map_rows.append((match_map_id, match_id, order, map_name, winner))
                match_map_id += 1

            maps_played = len(maps_this_match)
            for side_team_id in (team_a_id, team_b_id):
                for p in players_by_team[side_team_id]:
                    profile = ROLE_PROFILE[p["role"]]
                    kills = sum(RNG.randint(*profile["kills"]) // 2 for _ in range(maps_played)) + RNG.randint(0, 3)
                    deaths = sum(RNG.randint(*profile["deaths"]) // 2 for _ in range(maps_played)) + RNG.randint(0, 3)
                    assists = sum(RNG.randint(*profile["assists"]) // 2 for _ in range(maps_played)) + RNG.randint(0, 2)
                    stat_rows.append((stat_id, match_id, p["id"], kills, deaths, assists))
                    stat_id += 1

            match_id += 1

    for row in match_rows:
        mid, tid, mdate, a, b, asc, bsc = row
        out.append(
            "INSERT INTO matches (match_id, tournament_id, match_date, team_a_id, team_b_id, "
            f"team_a_score, team_b_score) VALUES ({mid}, {tid}, {sql_str(mdate)}, {a}, {b}, {asc}, {bsc});"
        )
    out.append("")
    for row in map_rows:
        mmid, mid, order, map_name, winner = row
        out.append(
            "INSERT INTO match_maps (match_map_id, match_id, map_order, map_name, winner_team_id) "
            f"VALUES ({mmid}, {mid}, {order}, {sql_str(map_name)}, {winner});"
        )
    out.append("")
    for row in stat_rows:
        sid, mid, plid, k, d, a = row
        out.append(
            "INSERT INTO player_match_stats (stat_id, match_id, player_id, kills, deaths, assists) "
            f"VALUES ({sid}, {mid}, {plid}, {k}, {d}, {a});"
        )
    out.append("")

    Path("seed/seed.sql").write_text("\n".join(out) + "\n")
    print(f"Wrote seed/seed.sql: {len(teams)} teams, {len(players)} players, "
          f"{len(match_rows)} matches, {len(map_rows)} maps, {len(stat_rows)} stat lines",
          file=sys.stderr)


if __name__ == "__main__":
    main()
